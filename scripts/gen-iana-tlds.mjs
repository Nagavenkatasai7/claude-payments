// Generates src/lib/iana-tlds.ts from the IANA root-zone TLD list (R6b).
// Usage: node scripts/gen-iana-tlds.mjs [path-to-downloaded-list]
// Without a path it fetches https://data.iana.org/TLD/tlds-alpha-by-domain.txt.
// The output is checked in; re-run it by hand to refresh the snapshot.
import { readFileSync, writeFileSync } from 'node:fs';
import { domainToUnicode } from 'node:url';

const SOURCE = 'https://data.iana.org/TLD/tlds-alpha-by-domain.txt';
const text = process.argv[2]
  ? readFileSync(process.argv[2], 'utf8')
  : await (await fetch(SOURCE)).text();
const lines = text.split('\n').map((l) => l.trim());
const version = (lines.find((l) => l.startsWith('#')) ?? '').replace(/^#\s*/, '');
const ascii = lines.filter((l) => l && !l.startsWith('#')).map((l) => l.toLowerCase());
if (ascii.length < 1000) throw new Error(`suspiciously short TLD list: ${ascii.length}`);
const unicode = ascii
  .filter((t) => t.startsWith('xn--'))
  .map((t) => domainToUnicode(t).normalize('NFKC').toLowerCase())
  .filter((u) => u && !u.startsWith('xn--'));
const all = [...new Set([...ascii, ...unicode])].sort();
const today = new Date().toISOString().slice(0, 10);
const out = `// GENERATED by scripts/gen-iana-tlds.mjs. Do not edit by hand.
// Source: ${SOURCE}
// IANA ${version}
// Fetched: ${today}
// ${ascii.length} TLDs, plus the Unicode form of each xn-- TLD (${unicode.length}), lower-cased.

export const IANA_TLDS: readonly string[] = ${JSON.stringify(all, null, 0).replace(/","/g, '", "')};
`;
writeFileSync(new URL('../src/lib/iana-tlds.ts', import.meta.url), out);
console.log(`wrote ${all.length} entries (${ascii.length} ascii + ${unicode.length} unicode)`);
